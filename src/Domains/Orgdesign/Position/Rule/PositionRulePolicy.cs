namespace Acme.Workforce.Orgdesign.Position.Rule;

using Acme.Workforce.Kit.Numbers;

/// <summary>Functions of position rule policy.</summary>
public static class PositionRulePolicy
{
    /// <summary>Puts a position rule code in its canonical PR- form.</summary>
    public static string NormalizePositionRuleCode(string code)
    {
        var clean = code.Trim().ToUpperInvariant();
        if (clean == "")
        {
            return "";
        }
        if (clean.StartsWith("PR-", StringComparison.Ordinal))
        {
            return clean;
        }
        return $"PR-{clean.Replace(" ", "-", StringComparison.Ordinal)}";
    }

    public static string PositionRuleBucket(double valueValue)
    {
        var lower = Numbers.RoundTo(valueValue - 2.5, 5.0);
        return $"{lower}-{lower + 5.0}";
    }

    public static int PositionRuleSpan(int start, int end)
    {
        if (end < start)
        {
            return 0;
        }
        var span = end - start;
        if (span < 3600)
        {
            return 0;
        }
        return span / 60;
    }
}
