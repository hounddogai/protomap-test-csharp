namespace Acme.Workforce.Orgdesign.Span.Preference;

using Acme.Workforce.Kit.Numbers;

/// <summary>Functions of span review policy.</summary>
public static class SpanReviewPolicy
{
    public static string SpanReviewBucket(double valueValue)
    {
        var lower = Numbers.RoundTo(valueValue - 2.5, 5.0);
        return $"{lower}-{lower + 5.0}";
    }

    /// <summary>Puts a span review code in its canonical SR- form.</summary>
    public static string NormalizeSpanReviewCode(string code)
    {
        var clean = code.Trim().ToUpperInvariant();
        if (clean == "")
        {
            return "";
        }
        if (clean.StartsWith("SR-", StringComparison.Ordinal))
        {
            return clean;
        }
        return $"SR-{clean.Replace(" ", "-", StringComparison.Ordinal)}";
    }

    public static int SpanReviewSpan(int start, int end)
    {
        if (end < start)
        {
            return 0;
        }
        var span = end - start;
        if (span < 900)
        {
            return 0;
        }
        return span / 86400;
    }
}
