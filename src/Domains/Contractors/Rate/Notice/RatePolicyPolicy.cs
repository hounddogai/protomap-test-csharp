namespace Acme.Workforce.Contractors.Rate.Notice;

/// <summary>Functions of rate policy policy.</summary>
public static class RatePolicyPolicy
{
    /// <summary>Puts a rate policy code in its canonical RP- form.</summary>
    public static string NormalizeRatePolicyCode(string code)
    {
        var clean = code.Trim().ToUpperInvariant();
        if (clean == "")
        {
            return "";
        }
        if (clean.StartsWith("RP-", StringComparison.Ordinal))
        {
            return clean;
        }
        return $"RP-{clean.Replace(" ", "-", StringComparison.Ordinal)}";
    }

    public static int RatePolicySpan(int start, int end)
    {
        if (end < start)
        {
            return 0;
        }
        var span = end - start;
        if (span < 900)
        {
            return 0;
        }
        return span / 86400;
    }
}
